    private void btnPalpiteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPalpiteActionPerformed
        // TODO add your handling code here:
        
        try {
            //pega o texto do campo e converte para numero (palpite do usuario)
            int palpite = Integer.parseInt(txtPalpite.getText());
            
            //validacao simples do palpite 
            if(palpite < 1 || palpite > 5) {
                lblMensagem.setText("O palpite deve ser entre 1 e 5.");
                return;
            }
            
            //logica principal
            if (palpite == valorSorteado){
                //Acertou
                lblMensagem.setText("ACERTOU!");
                btnPalpite.setEnabled(false); //desabilita o botao apos o acerto
                
            } else{
                //errou!!
                //exibe o numero sorteado conforme a imagem do dasafio 
                lblMensagem.setText("<html>ERROU! Eu pensei no valor **" + valorSorteado + "**</html>");
                btnPalpite.setEnabled(false);
            }
        } catch (NumberFormatException e){
            // mensagem de erro se o usuario digitar letras ou deixaar o campo vazio.
            lblMensagem.setText("Digite um numero, por favor.");
            
        }
     
    }//GEN-LAST:event_btnPalpiteActionPerformed

