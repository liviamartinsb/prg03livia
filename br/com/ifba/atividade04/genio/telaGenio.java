    // metodo que usa Math.random() para gerar o numero secreto.
    private void sortearValor(){
        //gera um numero inteiro de 1 a 5
        // Math.random() gera[0.0,1.0). Multiplicando por 5, trunca (0 a 4), e soma 1(1 a 5)
        valorSorteado = (int)(Math.random() * 5) + 1;
    }
    
